// LayoutSourcePath places every rendered document by the path the order
// names (stuttgart-things/claims#92). See internal/layout.
const LayoutSourcePath = "source-path"

// validLayouts are the values --layout accepts; "" is the classic layout
// (--output-dir + --filename-pattern + claims/registry.yaml).
var validLayouts = []string{"", LayoutSourcePath}

func validateLayout(config *RenderConfig) error {
	known := false
	for _, l := range validLayouts {
		if config.Layout == l {
			known = true
		}
	}
	if !known {
		return fmt.Errorf("unknown --layout %q (want %s)", config.Layout, LayoutSourcePath)
	}
	if config.Layout == "" {
		return nil
	}
	if config.Interactive {
		return fmt.Errorf("--layout %s runs non-interactively only (add --non-interactive)", config.Layout)
	}
	if config.SingleFile {
		return fmt.Errorf("--single-file does not apply to --layout %s: the order names its files", config.Layout)
	}
	if config.FileMode == "append" {
		return fmt.Errorf("--file-mode append does not apply to --layout %s: an order's files are new", config.Layout)
	}
	return nil
}

// layoutOrder is one rendered template under the source-path layout.
type layoutOrder struct {
	Result   RenderResult
	Template *templates.ClaimTemplate
	Params   map[string]interface{}
	Files    []layout.File
}

// param returns a parameter as the order used it: the given value, else the
// template's default.
func (o layoutOrder) param(names ...string) string {
	for _, n := range names {
		if v, ok := o.Params[n]; ok && fmt.Sprintf("%v", v) != "" {
			return fmt.Sprintf("%v", v)
		}
	}
	if o.Template != nil {
		for _, n := range names {
			for _, p := range o.Template.Spec.Parameters {
				if p.Name == n && p.Default != nil && fmt.Sprintf("%v", p.Default) != "" {
					return fmt.Sprintf("%v", p.Default)
				}
			}
		}
	}
	return ""
}

// annotation returns an annotation of the order's first document.
func (o layoutOrder) annotation(key string) string {
	if len(o.Files) == 0 || len(o.Files[0].Documents) == 0 {
		return ""
	}
	return o.Files[0].Documents[0].Annotations[key]
}

func (o layoutOrder) isVM() bool {
	return o.Template != nil && o.Template.Spec.Type == "xr-native-vm"
}

// layoutConvention is the branch, title and body an order's pull request
// gets unless --git-branch, --pr-title or --pr-description say otherwise.
type layoutConvention struct {
	Branch string
	Title  string
	Body   string
}

// conventionFor follows the Backstage templates, so the repository's checks
// and its release tooling treat the PR like theirs: a VM order like
// create-vm's (branch vm-<name>; feat:, a chore: title is dropped by the
// release tooling; "(MERGE = BAU)"), anything else alike.
func conventionFor(orders []layoutOrder) layoutConvention {
	o := orders[0]
	name := o.param("name")
	if name == "" {
		name = o.Result.ResourceName
	}

	var files strings.Builder
	for _, ord := range orders {
		for _, f := range ord.Files {
			_, _ = fmt.Fprintf(&files, "- `%s`\n", f.Path)
		}
	}

	if o.isVM() && len(orders) == 1 {
		lab := o.param("templateName", "lab")
		useCase := o.param("use_case")
		size := o.param("size")
		cluster := o.annotation(layout.AnnotationManagementCluster)
		ordersDir := path.Dir(o.annotation(layout.AnnotationSourcePath))

		var b strings.Builder
		_, _ = fmt.Fprintf(&b, "Order for the VM `%s`, written by the claims CLI from the claim-machinery-api template `%s`.\n\n", name, o.Result.TemplateName)
		b.WriteString("| Decision | Value |\n|---|---|\n")
		_, _ = fmt.Fprintf(&b, "| Lab | `%s` |\n| Size | `%s` |\n| Use case | `%s` |\n\n", lab, size, useCase)
		_, _ = fmt.Fprintf(&b, "**Merging builds the VM.** Flux applies the order on `%s`, Crossplane creates the VM, "+
			"and its AnsibleRun sets it up once it has an address. The address is in the XR's status "+
			"(`kubectl get nativeproxmoxvm,nativevspherevm %s-vm` on `%s`) and `ssh sthings@IP` works with the address from there.\n\n",
			cluster, name, cluster)
		_, _ = fmt.Fprintf(&b, "This Kustomization does not prune, and the order carries `prune: disabled`. "+
			"Removing the VM is a deliberate two-step, see `%s/README.md`.\n\n", ordersDir)
		b.WriteString("Files:\n\n")
		b.WriteString(files.String())
		b.WriteString("\n---\n*Generated by claims CLI*\n")
		return layoutConvention{
			Branch: "vm-" + name,
			Title:  fmt.Sprintf("feat(machinery): VM %s (%s, %s) (MERGE = BAU)", name, useCase, lab),
			Body:   b.String(),
		}
	}

	var names []string
	for _, ord := range orders {
		names = append(names, fmt.Sprintf("%s %s", ord.Result.TemplateName, ord.Result.ResourceName))
	}
	var b strings.Builder
	b.WriteString("Rendered by the claims CLI from claim-machinery-api:\n\n")
	for _, n := range names {
		_, _ = fmt.Fprintf(&b, "- **%s**\n", n)
	}
	b.WriteString("\nFiles:\n\n")
	b.WriteString(files.String())
	b.WriteString("\n---\n*Generated by claims CLI*\n")
	return layoutConvention{
		Branch: fmt.Sprintf("claim-%s-%s", o.Result.TemplateName, name),
		Title:  fmt.Sprintf("feat(claims): %s", strings.Join(names, ", ")),
		Body:   b.String(),
	}
}

// planLayout maps each rendered template's documents to files.
func planLayout(results []RenderResult, templateParams []params.TemplateParams, lookup map[string]*templates.ClaimTemplate) ([]layoutOrder, error) {
	var orders []layoutOrder
	seen := map[string]string{}
	for i, r := range results {
		if r.Error != nil {
			return nil, fmt.Errorf("%s did not render; nothing written: %w", r.TemplateName, r.Error)
		}
		files, err := layout.Plan(r.Content)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", r.TemplateName, err)
		}
		for _, f := range files {
			if other, ok := seen[f.Path]; ok {
				return nil, fmt.Errorf("%s and %s both write %s", other, r.TemplateName, f.Path)
			}
			seen[f.Path] = r.TemplateName
		}
		var p map[string]interface{}
		if i < len(templateParams) {
			p = templateParams[i].Parameters
		}
		orders = append(orders, layoutOrder{Result: r, Template: lookup[r.TemplateName], Params: p, Files: files})
	}
	return orders, nil
}

func allFiles(orders []layoutOrder) []layout.File {
	var files []layout.File
	for _, o := range orders {
		files = append(files, o.Files...)
	}
	return files
}

// runSourcePathLayout writes the orders under the source-path layout and, if
// asked, commits them on a branch, pushes and opens the pull request. No
// claims/registry.yaml: the order's file with its annotations is the record.
func runSourcePathLayout(orders []layoutOrder, config *RenderConfig) error {
	conv := conventionFor(orders)
	files := allFiles(orders)

	if config.DryRun {
		changes, err := layout.Kustomizations(config.OutputDir, files)
		if err != nil {
			return err
		}
		printLayoutDryRun(files, changes, conv, config)
		return nil
	}

	git := config.GitConfig != nil && (config.GitConfig.Commit || config.GitConfig.Push)
	repoRoot := config.OutputDir
	var g *gitops.GitOps
	var user, prevBranch string

	if git {
		var token string
		var err error
		if config.GitConfig.Push {
			user, token, err = gitops.ResolveCredentials(config.GitConfig.User, config.GitConfig.Token)
			if err != nil {
				return err
			}
		} else {
			user, token = gitops.ResolveCredentialsOptional(config.GitConfig.User, config.GitConfig.Token)
		}

		if config.GitConfig.RepoURL != "" {
			fmt.Printf("Cloning %s...\n", config.GitConfig.RepoURL)
			var tmpDir string
			g, tmpDir, err = gitops.Clone(config.GitConfig.RepoURL, user, token)
			if err != nil {
				return err
			}
			defer func() { _ = g.Cleanup() }()
			repoRoot = tmpDir
		} else {
			root, err := findRepoRoot(config.OutputDir)
			if err != nil {
				return fmt.Errorf("--layout %s with git needs --output-dir in a git repository: %w", LayoutSourcePath, err)
			}
			abs, _ := filepath.Abs(config.OutputDir)
			if abs != root {
				return fmt.Errorf("--layout %s: --output-dir must be the repository root (%s), the order's paths are relative to it", LayoutSourcePath, root)
			}
			g, err = gitops.New(root, user, token)
			if err != nil {
				return err
			}
		}

		prevBranch = currentBranch(g)
		branch := config.GitConfig.Branch
		if branch == "" {
			branch = conv.Branch
			config.GitConfig.Branch = branch
		}
		if config.GitConfig.CreateBranch || branch == conv.Branch {
			fmt.Printf("Creating branch: %s\n", branch)
			if err := g.CreateBranch(branch); err != nil {
				return err
			}
		} else {
			fmt.Printf("Checking out branch: %s\n", branch)
			if err := g.CheckoutBranch(branch); err != nil {
				return err
			}
		}
	}

	changes, err := layout.Kustomizations(repoRoot, files)
	if err != nil {
		return err
	}
	if err := layout.Write(repoRoot, files, changes); err != nil {
		return err
	}

	var written []string
	for _, f := range files {
		written = append(written, filepath.Join(repoRoot, filepath.FromSlash(f.Path)))
		fmt.Printf("Saved: %s\n", f.Path)
	}
	for _, c := range changes {
		written = append(written, filepath.Join(repoRoot, filepath.FromSlash(c.Path)))
		fmt.Printf("Appended to %s: %s\n", c.Path, strings.Join(c.Lines, ", "))
	}

	if !git {
		return nil
	}

	fmt.Println("Staging files...")
	if err := g.AddFiles(written); err != nil {
		return err
	}
	message := config.GitConfig.Message
	if message == "" {
		message = conv.Title
	}
	fmt.Printf("Committing: %s\n", message)
	if err := g.Commit(message, user, ""); err != nil {
		return err
	}
	fmt.Println(successStyle.Render("Committed successfully"))

	if !config.GitConfig.Push {
		return nil
	}
	remote := config.GitConfig.Remote
	if remote == "" {
		remote = "origin"
	}
	fmt.Printf("Pushing %s to %s...\n", config.GitConfig.Branch, remote)
	if err := g.Push(remote, config.GitConfig.Branch); err != nil {
		return pushFailed(err, g, remote, config.GitConfig.Branch, prevBranch, prBaseOf(config.PRConfig), config.GitConfig.RepoURL != "")
	}
	fmt.Println(successStyle.Render("Pushed successfully"))

	if config.PRConfig == nil || !config.PRConfig.Create {
		return nil
	}
	if err := gitops.CheckGitHubAuth(config.GitConfig.token()); err != nil {
		return err
	}
	pr := gitops.PRConfig{
		Title:       config.PRConfig.Title,
		Description: config.PRConfig.Description,
		Labels:      config.PRConfig.Labels,
		BaseBranch:  config.PRConfig.BaseBranch,
		HeadBranch:  config.GitConfig.Branch,
		Token:       config.GitConfig.token(),
	}
	if pr.Title == "" {
		pr.Title = conv.Title
	}
	if pr.Description == "" {
		pr.Description = conv.Body
	}
	if pr.BaseBranch == "" {
		pr.BaseBranch = "main"
	}
	fmt.Println("Creating pull request...")
	res, err := gitops.CreatePR(pr, g.RepoPath)
	if err != nil {
		return prFailed(err, pr.HeadBranch, pr.BaseBranch)
	}
	fmt.Println(successStyle.Render(fmt.Sprintf("Created PR: %s", res.URL)))
	if config.PRConfig.Merge {
		return mergeCreatedPR(res.URL, config.GitConfig.token())
	}
	return nil
}

// printLayoutDryRun shows every file, the kustomization diff and the
// branch/title the PR would get.
func printLayoutDryRun(files []layout.File, changes []*layout.KustomizationChange, conv layoutConvention, config *RenderConfig) {
	fmt.Println("\n=== DRY RUN - No files written ===")
	for _, f := range files {
		action := "write"
		if _, err := os.Stat(filepath.Join(config.OutputDir, filepath.FromSlash(f.Path))); err == nil {
			action = "REFUSE (exists already)"
		}
		fmt.Printf("Would %s: %s\n", action, f.Path)
		fmt.Println(yamlStyle.Render(strings.TrimSpace(f.Content())))
		fmt.Println()
	}
	if len(changes) == 0 {
		fmt.Println("No kustomization.yaml next to the files: nothing to append.")
	}
	for _, c := range changes {
		fmt.Printf("Would append to %s:\n", c.Path)
		for _, l := range c.Lines {
			fmt.Printf("+%s\n", l)
		}
		fmt.Println()
	}
	branch, title := conv.Branch, conv.Title
	if config.GitConfig != nil && config.GitConfig.Branch != "" {
		branch = config.GitConfig.Branch
	}
	if config.PRConfig != nil && config.PRConfig.Title != "" {
		title = config.PRConfig.Title
	}
	fmt.Printf("Branch: %s\nPR title: %s\n", branch, title)
}
