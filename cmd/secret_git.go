package cmd

import (
	"context"
	"fmt"
	"io"
	"strings"
	"time"

	"github.com/spf13/cobra"

	"github.com/stuttgart-things/claims/internal/gitops"
)

// The git side of claims secret: the changed SOPS files go onto a branch,
// are committed, pushed and (--create-pr) proposed as a PR, as render and
// delete do. Commit messages and PR texts name paths and keys, never values
// or hashes.

// secretGit holds the git flags of one command.
type secretGit struct {
	branch   string
	message  string
	remote   string
	user     string
	token    string
	createPR bool
	prTitle  string
	prBase   string
	labels   []string
}

func addSecretGitFlags(c *cobra.Command, g *secretGit) {
	f := c.Flags()
	f.StringVar(&g.branch, "git-branch", "", "Commit on a new branch with this name (default with --create-pr: secret/<command>-<lab>-<time>)")
	f.StringVar(&g.message, "git-message", "", "Commit message (default: generated, paths and keys only)")
	f.StringVar(&g.remote, "git-remote", "origin", "Git remote to push to")
	f.StringVar(&g.user, "git-user", "", "Git username (or GIT_USER/GITHUB_USER env)")
	f.StringVar(&g.token, "git-token", "", "Git token (or GIT_TOKEN/GITHUB_TOKEN env, or gh auth token)")
	f.BoolVar(&g.createPR, "create-pr", false, "Commit on a new branch, push it and open a pull request")
	f.StringVar(&g.prTitle, "pr-title", "", "PR title (default: generated)")
	f.StringVar(&g.prBase, "pr-base", "main", "Base branch of the PR")
	f.StringSliceVar(&g.labels, "pr-labels", nil, "PR labels (comma-separated)")
	addPreflightFlag(c)
}

// enabled reports whether the command commits at all (else it only changes
// the working tree and the user commits).
func (g *secretGit) enabled() bool { return g.createPR || g.branch != "" }

// preflight checks the checkout, the token and the PR permission before
// anything is written.
func (g *secretGit) preflight(ctx context.Context, root string) error {
	if !g.enabled() || skipPreflight {
		return nil
	}
	r := &preflightReport{}
	checkGit(ctx, r, gitPreflight{
		RepoRoot: root, Remote: g.remote, Branch: g.branchName("", ""), CreateBranch: true,
		Push: true, PR: g.createPR, User: g.user, Token: g.token,
	})
	return finishPreflight(r)
}

// branchStamp is fixed per run so preflight and commit agree on the name.
var branchStamp = time.Now().UTC().Format("20060102-150405")

func (g *secretGit) branchName(command, lab string) string {
	if g.branch != "" {
		return g.branch
	}
	if command == "" {
		return "" // preflight without a name: the timestamped branch cannot exist
	}
	return fmt.Sprintf("secret/%s-%s-%s", command, lab, branchStamp)
}

// secretChange describes the commit.
type secretChange struct {
	Command string // sync-vault-to-sops, set, unset, rotate
	Lab     string
	Files   []string // absolute paths of the changed files
	Subject string   // commit subject / PR title
	Body    string   // commit body / PR description (no values!)
}

// commit puts change onto a branch, commits, pushes and opens the PR.
func (g *secretGit) commit(root string, change secretChange, out io.Writer) error {
	if !g.enabled() || len(change.Files) == 0 {
		return nil
	}
	user, token, err := gitops.ResolveCredentials(g.user, g.token)
	if err != nil {
		return err
	}
	repo, err := gitops.New(root, user, token)
	if err != nil {
		return err
	}
	prev := currentBranch(repo)
	branch := g.branchName(change.Command, change.Lab)
	_, _ = fmt.Fprintf(out, "Creating branch %s\n", branch)
	if err := repo.CreateBranch(branch); err != nil {
		return err
	}
	if err := repo.AddFiles(change.Files); err != nil {
		return err
	}
	msg := g.message
	if msg == "" {
		msg = change.Subject + "\n\n" + change.Body
	}
	if err := repo.Commit(msg, user, ""); err != nil {
		return err
	}
	_, _ = fmt.Fprintln(out, successStyle.Render("Committed "+plural(len(change.Files), "file")))
	remote := g.remote
	if remote == "" {
		remote = "origin"
	}
	if err := repo.Push(remote, branch); err != nil {
		return pushFailed(err, repo, remote, branch, prev, g.prBase, false)
	}
	_, _ = fmt.Fprintf(out, "Pushed %s to %s\n", branch, remote)
	if !g.createPR {
		return nil
	}
	title := g.prTitle
	if title == "" {
		title = change.Subject
	}
	pr, err := gitops.CreatePR(gitops.PRConfig{
		Title:       title,
		Description: change.Body + "\n\n---\n*Generated by claims secret " + strings.ReplaceAll(change.Command, "-", " ") + " (no values, no hashes)*\n",
		Labels:      g.labels,
		BaseBranch:  g.prBase,
		HeadBranch:  branch,
		Token:       token,
	}, root)
	if err != nil {
		return prFailed(err, branch, g.prBase)
	}
	_, _ = fmt.Fprintln(out, successStyle.Render("Created PR: "+pr.URL))
	return nil
}
